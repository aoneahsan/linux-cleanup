#!/usr/bin/env bash
# Stale node_modules finder — interactive only.
# Scans project search roots and lists node_modules whose project dir has not
# had a source-file change in $DAYS+ days. User picks which to delete.

# Filled at run time by _nm_load_roots from project-roots.txt plus the default
# code directories that exist (lib/roots.sh). Never a hardcoded layout.
NM_SEARCH_ROOTS=()

_nm_load_roots() {
  load_project_roots
  NM_SEARCH_ROOTS=(${ROOTS_LOADED[@]+"${ROOTS_LOADED[@]}"})
}

# safe_rm_node_modules <path> — the ONE sanctioned delete inside a protected
# tree. Every search root lives under ~/Documents, which safe_rm refuses as a
# whole subtree, so before 1.5.0 this finder listed candidates but could never
# delete one. Accepts only: a real directory (not a symlink) named exactly
# node_modules, with a package.json beside it, whose resolved path is inside
# one of NM_SEARCH_ROOTS. Everything else is refused.
safe_rm_node_modules() {
  local target="$1" real parent root inside=0
  (( ${#NM_SEARCH_ROOTS[@]} )) || _nm_load_roots
  if [[ "$(basename -- "$target")" != node_modules || -L "$target" || ! -d "$target" ]]; then
    ui_err "REFUSE: not a node_modules directory: $target"; return 1
  fi
  real="$(realpath -e -- "$target" 2>/dev/null)" || { ui_err "REFUSE: cannot resolve: $target"; return 1; }
  parent="$(dirname -- "$real")"
  if [[ ! -f "$parent/package.json" ]]; then
    ui_err "REFUSE: no package.json beside $target"; return 1
  fi
  for root in ${NM_SEARCH_ROOTS[@]+"${NM_SEARCH_ROOTS[@]}"}; do
    root="$(realpath -m -- "$root")"
    [[ "$real" == "$root"/* ]] && inside=1
  done
  if (( ! inside )); then
    ui_err "REFUSE: outside the node_modules search roots: $target"; return 1
  fi
  rm -rf -- "$real"
}

# _tree_activity_epoch <dir> — mtime (epoch) of the newest file in <dir>,
# skipping dependency, VCS and build-output trees. Empty when none found.
_tree_activity_epoch() {
  find "$1" \( -name node_modules -o -name .git -o -name dist -o -name build \
       -o -name .yarn -o -name .next -o -name coverage \) -prune \
       -o -type f -printf '%T@\n' 2>/dev/null | cut -d. -f1 | sort -n | tail -1
}

# Newest-file epoch per enclosing repo, so a monorepo is walked once.
declare -A _NM_REPO_EPOCH=()

# project_activity_age_days <project-dir> — days since any source file in the
# project (or, when a git repo tracks it, anywhere in that repo) changed. The
# project directory's own mtime only moves when top-level entries are added
# or removed, so a project edited daily in src/ used to look stale; and a
# monorepo workspace is only as idle as the repo it builds with. A repo that
# IGNORES the directory (a workspace-root repo) does not own it and is skipped.
project_activity_age_days() {
  local dir="$1" now newest top t
  now=$(date +%s)
  newest=$(_tree_activity_epoch "$dir")
  top=$(git -C "$dir" rev-parse --show-toplevel 2>/dev/null || true)
  if [[ -n "$top" && "$top" != "$dir" ]] && ! git -C "$top" check-ignore -q -- "$dir" 2>/dev/null; then
    if [[ -z "${_NM_REPO_EPOCH[$top]+set}" ]]; then
      _NM_REPO_EPOCH["$top"]=$(_tree_activity_epoch "$top")
    fi
    t=${_NM_REPO_EPOCH[$top]}
    [[ -n "$t" ]] && (( t > ${newest:-0} )) && newest=$t
  fi
  [[ -n "$newest" ]] || newest=$(stat -c %Y -- "$dir" 2>/dev/null || echo "$now")
  printf '%d' $(( (now - newest) / 86400 ))
}

run_stale_node_modules() {
  local days="${DAYS:-100}"
  ui_section "Stale node_modules (projects untouched ${days}+ days)"
  ui_warn "Interactive only — regenerable via 'yarn install'."

  _nm_load_roots
  if (( ${#NM_SEARCH_ROOTS[@]} == 0 )); then
    ui_info "No project roots found. Looked for: ${PROJECT_ROOT_DEFAULTS[*]/#$HOME/\~}"
    prompt_add_root project-roots.txt "Where do you keep your projects?" && _nm_load_roots
  fi
  if (( ${#NM_SEARCH_ROOTS[@]} == 0 )); then
    ui_info "Add one path per line to $(roots_config_dir)/project-roots.txt, then run this again."
    return
  fi
  local roots=("${NM_SEARCH_ROOTS[@]}")
  ui_info "Searching: ${roots[*]}"

  local nm_paths=() nm
  while IFS= read -r nm; do
    [[ -n "$nm" ]] && nm_paths+=("$nm")
  done < <(
    # .yarn/unplugged/<pkg>/node_modules belongs to a Yarn PnP install, not to
    # a project — never a candidate. .git never holds one.
    find "${roots[@]}" \( -name .yarn -o -name .git \) -prune \
      -o -name node_modules -type d -prune -print 2>/dev/null \
      | awk '!seen[$0]++'
  )
  if (( ${#nm_paths[@]} == 0 )); then
    ui_info "No node_modules found."
    return
  fi

  local stale=() parent age
  local -A nm_age=()
  for nm in "${nm_paths[@]}"; do
    parent="$(dirname "$nm")"
    age="$(project_activity_age_days "$parent")"
    if [[ "$age" =~ ^[0-9]+$ ]] && (( age >= days )); then
      stale+=("$nm")
      nm_age["$nm"]=$age
    fi
  done

  if (( ${#stale[@]} == 0 )); then
    ui_info "No node_modules in projects ${days}+ days stale."
    return
  fi

  # Sort by size descending for visibility
  local sized=()
  while IFS= read -r line; do sized+=("$line"); done < <(
    for nm in "${stale[@]}"; do
      printf '%s\t%s\n' "$(dir_bytes "$nm")" "$nm"
    done | sort -t$'\t' -k1,1 -nr
  )

  printf "${C_BLD}%4s %10s %8s  %s${C_RST}\n" "#" "SIZE" "AGE-d" "PROJECT"
  local i=1 ranked=() bytes path_part age_part
  for line in "${sized[@]}"; do
    bytes="${line%%$'\t'*}"
    path_part="${line#*$'\t'}"
    age_part="${nm_age[$path_part]}"
    printf "%4d %10s %8s  %s\n" "$i" "$(bytes_pretty "$bytes" | xargs)" "$age_part" "$(dirname "$path_part")"
    ranked+=("$path_part")
    ((i++))
    (( i > 200 )) && { ui_warn "(truncated to 200 entries)"; break; }
  done

  printf '\n%s\n' "Choose action:"
  printf '  %s\n' "a   delete ALL listed (regenerable via 'yarn install')"
  printf '  %s\n' "c   enter comma/range indexes (e.g. 1,3,5-7)"
  printf '  %s\n' "s   skip"
  local mode
  read -rp "> " mode

  delete_picks() {
    local -a picks=("$@")
    local total=0 b nm
    if ! ui_confirm "Confirm delete ${#picks[@]} node_modules?" n; then
      ui_info "aborted"; return
    fi
    for nm in "${picks[@]}"; do
      [[ -z "$nm" ]] && continue
      b=$(dir_bytes "$nm")
      if safe_rm_node_modules "$nm"; then
        total=$(( total + b ))
        ui_ok "deleted $nm"
      fi
    done
    ui_ok "Total freed: $(bytes_pretty "$total")"
  }

  case "$mode" in
    a) delete_picks "${ranked[@]}" ;;
    c)
      local idxs picks=() parts p k
      read -rp "Indexes: " idxs
      local IFS=','; parts=($idxs); unset IFS
      for p in "${parts[@]}"; do
        p="${p// /}"
        if [[ "$p" =~ ^([0-9]+)-([0-9]+)$ ]]; then
          for ((k=${BASH_REMATCH[1]}; k<=${BASH_REMATCH[2]}; k++)); do
            picks+=("${ranked[$((k-1))]:-}")
          done
        elif [[ "$p" =~ ^[0-9]+$ ]]; then
          picks+=("${ranked[$((p-1))]:-}")
        fi
      done
      delete_picks "${picks[@]}"
      ;;
    *) ui_info "skipped" ;;
  esac
}
